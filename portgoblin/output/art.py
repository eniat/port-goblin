ART_WIDTH = 48
DOOR_COLUMN = 36  # the door frame's left post; everything from here is the door
# Motion lines around the knocking fist.
KNOCK_CELLS = frozenset(
    [(8, 29), (8, 30), (8, 31), (10, 28), (10, 29), (10, 30), (12, 30), (12, 31)]
)


def is_knock(row: int, col: int) -> bool:
    return (row, col) in KNOCK_CELLS


def is_peeker(row: int, col: int) -> bool:
    """The face peeking round the door (rows 9 to 12) and its fingers on the door (13 to 16)."""
    face = 9 <= row <= 12 and 38 <= col <= 43 and not (col == 43 and row in (9, 12))
    fingers = 13 <= row <= 16 and 40 <= col <= 42
    return face or fingers


def is_door(row: int, col: int) -> bool:
    return col >= DOOR_COLUMN and not is_peeker(row, col)
